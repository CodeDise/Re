"""
Telegram Activity Logger & Database Channel Delivery
====================================================
Logs all user activity (Article Scraped, YouTube Summary, PDF Downloaded,
Payment Submissions) to Config.LOG_CHANNEL_ID.
For generated PDFs, uploads the document directly to Config.LOG_CHANNEL_ID
first, then delivers it to the requesting user using the cached Telegram file_id.
"""

import html
import io
import logging
from datetime import datetime, timezone
from typing import Optional
from pyrogram import Client
from pyrogram.types import User, Message, InlineKeyboardMarkup
from config import Config

logger = logging.getLogger(__name__)


def _format_user_block(user: User, is_premium: bool) -> str:
    full_name = html.escape(
        f"{user.first_name or ''} {user.last_name or ''}".strip() or "Unknown User"
    )
    username_str = f"@{html.escape(user.username)}" if user.username else "<i>None</i>"
    tier_badge = "💎 Premium User" if is_premium else "🆓 Free Tier User"
    return (
        f"👤 <b>User:</b> <a href='tg://user?id={user.id}'>{full_name}</a>\n"
        f"🏷 <b>Username:</b> {username_str}\n"
        f"🆔 <b>User ID:</b> <code>{user.id}</code>\n"
        f"⭐ <b>Status:</b> {tier_badge}"
    )


async def log_activity(
    client: Client,
    user: User,
    is_premium: bool,
    action: str,
    original_url: str,
    title: str,
    telegraph_url: Optional[str] = None,
    extra_note: Optional[str] = None,
) -> Optional[Message]:
    """
    Send a structured activity log message to Config.LOG_CHANNEL_ID.
    Includes User Details, Action, Original URL, Title, Telegraph IV Link, and Tier Status.
    """
    if not Config.LOG_CHANNEL_ID:
        return None

    now_str = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M:%S UTC")
    safe_title = html.escape(title[:160])
    safe_url = html.escape(original_url)
    safe_action = html.escape(action)

    lines = [
        "📋 <b>#ACTIVITY_LOG — CleanReader Bot</b>",
        "━━━━━━━━━━━━━━━━━━━━━━",
        _format_user_block(user, is_premium),
        "━━━━━━━━━━━━━━━━━━━━━━",
        f"⚡ <b>Action:</b> {safe_action}",
        f"📰 <b>Title:</b> {safe_title}",
        f"🔗 <b>Original URL:</b> <a href='{safe_url}'>Source Link</a>",
    ]
    if telegraph_url:
        lines.append(
            f"⚡ <b>Telegraph IV:</b> <a href='{html.escape(telegraph_url)}'>Instant View</a>"
        )
    if extra_note:
        lines.append(f"📝 <b>Details:</b> {html.escape(extra_note)}")
    lines.append(f"🕒 <b>Timestamp:</b> <code>{now_str}</code>")

    try:
        return await client.send_message(
            chat_id=Config.LOG_CHANNEL_ID,
            text="\n".join(lines),
            disable_web_page_preview=True,
        )
    except Exception as exc:
        logger.error("Failed to send activity log to %s: %s", Config.LOG_CHANNEL_ID, exc)
        return None


async def upload_pdf_to_log_and_deliver(
    client: Client,
    user: User,
    target_chat_id: int,
    is_premium: bool,
    pdf_bytes: bytes,
    filename: str,
    title: str,
    original_url: str,
    telegraph_url: Optional[str] = None,
    reply_to_message_id: Optional[int] = None,
) -> Optional[Message]:
    """
    1. Uploads the generated PDF document directly to Config.LOG_CHANNEL_ID first
       with full user & article metadata caption.
    2. Re-uses the uploaded document's `file_id` (or falls back to direct stream)
       to deliver the clean PDF to the user immediately.
    """
    now_str = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M:%S UTC")
    safe_title = html.escape(title[:150])
    safe_url = html.escape(original_url)

    log_caption = (
        "📥 <b>#PDF_EXPORT — CleanReader Archive</b>\n"
        "━━━━━━━━━━━━━━━━━━━━━━\n"
        f"{_format_user_block(user, is_premium)}\n"
        "━━━━━━━━━━━━━━━━━━━━━━\n"
        f"📄 <b>Document:</b> {safe_title}\n"
        f"🔗 <b>Source URL:</b> <a href='{safe_url}'>Original Article</a>\n"
        + (
            f"⚡ <b>Telegraph IV:</b> <a href='{html.escape(telegraph_url)}'>Instant View</a>\n"
            if telegraph_url
            else ""
        )
        + f"🕒 <b>Exported:</b> <code>{now_str}</code>"
    )

    user_caption = (
        f"📕 <b>{safe_title}</b>\n\n"
        f"🔗 <a href='{safe_url}'>Original Source</a>"
        + (
            f"  |  ⚡ <a href='{html.escape(telegraph_url)}'>Instant View</a>"
            if telegraph_url
            else ""
        )
        + f"\n✨ <i>Generated by @{Config.BOT_USERNAME}</i>"
    )

    pdf_stream = io.BytesIO(pdf_bytes)
    pdf_stream.name = filename

    logged_msg: Optional[Message] = None
    if Config.LOG_CHANNEL_ID:
        try:
            logged_msg = await client.send_document(
                chat_id=Config.LOG_CHANNEL_ID,
                document=pdf_stream,
                file_name=filename,
                caption=log_caption,
            )
        except Exception as exc:
            logger.error(
                "Could not upload PDF to LOG_CHANNEL_ID (%s): %s",
                Config.LOG_CHANNEL_ID,
                exc,
            )

    # Deliver to user via cached file_id from LOG_CHANNEL_ID if available
    if logged_msg and logged_msg.document:
        return await client.send_document(
            chat_id=target_chat_id,
            document=logged_msg.document.file_id,
            caption=user_caption,
            reply_to_message_id=reply_to_message_id,
        )

    # Fallback direct upload if LOG_CHANNEL_ID upload failed
    fallback_stream = io.BytesIO(pdf_bytes)
    fallback_stream.name = filename
    return await client.send_document(
        chat_id=target_chat_id,
        document=fallback_stream,
        file_name=filename,
        caption=user_caption,
        reply_to_message_id=reply_to_message_id,
    )
